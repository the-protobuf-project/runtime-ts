// Writes the API reference of every package's README from its own doc
// comments. It reads the declarations tsc emits, so run it after a build.
//
//   bun tools/docgen.ts           rewrite the reference in each README
//   bun tools/docgen.ts --check   fail if a README is out of date (CI)

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const start = "<!-- api:start -->";
const end = "<!-- api:end -->";

/** One exported declaration. */
interface Declaration {
  name: string;
  kind: string;
  summary: string;
}

const declaration =
  /(\/\*\*(?:(?!\*\/)[\s\S])*\*\/)?\s*export (?:declare )?(?:abstract )?(function|class|interface|type|const|enum) (\w+)/g;
const reexport = /export (type )?\{([^}]*)\} from "(\.[^"]+)";/g;
const starExport = /export \* from "(\.[^"]+)";/g;

/** The first sentence of a JSDoc block, on one line, without tags or code. */
function summary(doc: string | undefined): string {
  if (!doc) return "";
  const text = doc
    .replace(/^\/\*\*|\*\/$/g, "")
    .split("\n")
    .map((line) => line.replace(/^\s*\* ?/, ""))
    .join("\n")
    .split(/\n\s*\n|\n@|```/)[0]
    ?.replace(/\s+/g, " ")
    .trim();
  if (!text) return "";
  const sentence = /^(.+?[.!?])(\s|$)/.exec(text)?.[1] ?? text;
  return sentence.replaceAll("|", "\\|");
}

/** Every declaration a .d.ts file exports, following re-exports. */
function exportsOf(file: string, seen = new Set<string>()): Map<string, Declaration> {
  const out = new Map<string, Declaration>();
  if (seen.has(file)) return out;
  seen.add(file);
  const text = readFileSync(file, "utf8");
  for (const m of text.matchAll(declaration)) {
    const [, doc, kind, name] = m as unknown as [string, string | undefined, string, string];
    out.set(name, { name, kind, summary: summary(doc) });
  }
  for (const m of text.matchAll(reexport)) {
    const [, , list, from] = m as unknown as [string, string | undefined, string, string];
    const target = exportsOf(resolve(file, from), seen);
    for (const item of list.split(",").map((s) => s.trim().replace(/^type /, ""))) {
      if (!item) continue;
      const [local, alias] = item.split(/\s+as\s+/) as [string, string | undefined];
      const found = target.get(local);
      if (found) out.set(alias ?? local, { ...found, name: alias ?? local });
    }
  }
  for (const m of text.matchAll(starExport)) {
    for (const [name, d] of exportsOf(resolve(file, m[1] as string), seen)) out.set(name, d);
  }
  return out;
}

function resolve(from: string, spec: string): string {
  return join(dirname(from), spec.replace(/\.(js|ts)$/, ".d.ts"));
}

/** The API reference of one package, as Markdown. */
function reference(dir: string): string {
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8")) as {
    name: string;
    exports: Record<string, { types?: string }>;
  };
  const sections: string[] = [];
  for (const [subpath, target] of Object.entries(pkg.exports)) {
    if (!target.types) continue;
    const decls = [...exportsOf(join(dir, target.types)).values()];
    const name = subpath === "." ? pkg.name : `${pkg.name}/${subpath.slice(2)}`;
    const rows = decls.map((d) => `| \`${d.name}\` | ${d.kind} | ${d.summary} |`);
    sections.push(`### \`${name}\`\n\n| Export | Kind | Description |\n| --- | --- | --- |\n${rows.join("\n")}`);
  }
  return `${start}\n<!-- Generated by tools/docgen.ts from the doc comments. Do not edit. -->\n\n${sections.join("\n\n")}\n\n${end}`;
}

const check = process.argv.includes("--check");
let stale = 0;
for (const name of readdirSync("packages")) {
  const dir = join("packages", name);
  const readme = join(dir, "README.md");
  const text = readFileSync(readme, "utf8");
  const from = text.indexOf(start);
  const to = text.indexOf(end);
  if (from < 0 || to < 0) throw new Error(`${readme} has no ${start} ... ${end} block`);
  const next = text.slice(0, from) + reference(dir) + text.slice(to + end.length);
  if (next === text) continue;
  stale++;
  if (check) console.error(`${readme} is out of date: run bun run docs`);
  else writeFileSync(readme, next);
}
if (check && stale > 0) process.exit(1);
